@app.get("/ask")
def ask(question: str, model: str | None = None):

    question = question.strip()
    available_models = list_available_models()
    selected_model = model or OLLAMA_MODEL

    if selected_model not in available_models:
        raise HTTPException(
            status_code=400,
            detail=f"Model '{selected_model}' is not currently installed in Ollama.",
        )

    # --------------------------------------------------------
    # Validate question
    # --------------------------------------------------------

    if not question:

        return {
            "question": question,

            "answer": (
                "Please provide a developer or DevOps "
                "question."
            ),

            "diagnosis": None,

            "digital_twin": None,

            "sources": [],

            "ai": {
                "model": selected_model,
                "latency_seconds": None,
                "error": None,
            },
        }

    # --------------------------------------------------------
    # 1. Collect live environment telemetry
    # --------------------------------------------------------

    digital_twin = get_digital_twin()

    # Record the snapshot because /ask is also an
    # observability event.
    record_telemetry(digital_twin)

    # --------------------------------------------------------
    # 2. Produce deterministic diagnosis
    # --------------------------------------------------------

    diagnosis = build_diagnosis(
        digital_twin
    )

    # --------------------------------------------------------
    # 3. Orchestrate application services
    # --------------------------------------------------------

    orchestration = orchestrate_request(
        question=question,
        digital_twin=digital_twin,
        diagnosis=diagnosis,
        rag_results=RAG_RESULTS,
    )

    documents = orchestration["retrieved_context"]
    try:
        repository_sources = search_sourcegraph(question, limit=8)
    except Exception:
        repository_sources = []

    # --------------------------------------------------------
    # 4. Build grounded prompt
    # --------------------------------------------------------

    prompt = build_prompt(
        question=question,
        digital_twin=digital_twin,
        diagnosis=diagnosis,
        documents=documents,
        sourcegraph_sources=repository_sources,
    )

    # --------------------------------------------------------
    # 5. Ask local AI model
    # --------------------------------------------------------

    ai_error = None
    latency = None

    try:

        answer, latency = ask_ollama(
            prompt,
            selected_model,
        )

    except requests.exceptions.Timeout:

        ai_error = (
            "The local AI model timed out. "
            "Live telemetry and deterministic diagnosis "
            "are still available."
        )

        answer = (
            "The local AI model took too long to respond. "
            "Review the returned diagnosis and Digital Twin "
            "telemetry for the current environment state."
        )

    except requests.exceptions.ConnectionError as exc:

        ai_error = (
            "Could not connect to Ollama at "
            f"{OLLAMA_URL}: {exc}"
        )

        answer = (
            "The local AI model is unavailable. "
            "Make sure the Ollama container is running "
                f"and model '{selected_model}' is available."
        )

    except requests.exceptions.HTTPError as exc:

        ai_error = str(exc)

        answer = (
            "Ollama returned an HTTP error while processing "
            "the request. The deterministic diagnosis and "
            "Digital Twin telemetry are still available."
        )

    except requests.exceptions.RequestException as exc:

        ai_error = str(exc)

        answer = (
            "The local AI model could not process the request. "
            "The deterministic diagnosis and Digital Twin "
            "telemetry are still available."
        )

    except Exception as exc:

        ai_error = str(exc)

        print(
            f"Ollama unexpected error: {exc}"
        )

        answer = (
            "An unexpected error occurred while generating "
            "the AI response. The deterministic diagnosis "
            "and Digital Twin telemetry are still available."
        )

    # --------------------------------------------------------
    # 6. Return complete observability response
    # --------------------------------------------------------

    return {
        "question": question,

        "answer": answer,

        "diagnosis": diagnosis,

        "digital_twin": digital_twin,

        "sources": documents,

        "sourcegraph": {
            "status": sourcegraph_status(),
            "results": repository_sources,
        },

        "ai": {
            "model": selected_model,
            "latency_seconds": latency,
            "error": ai_error,
        },
    }



