@app.post("/compare")
def compare(request: CompareRequest):
    question = request.question.strip()

    if not question:
        return {
            "error": "Question cannot be empty."
        }

    category = classify_question(question)

    context = build_context(question)

    prompt = build_combined_prompt(
        question,
        context,
    )

    responses = run_all_models(prompt)

    evaluated = evaluate_all(
        question,
        category,
        responses,
        context,
    )

    comparison = compare_models(
        evaluated,
        category,
    )

    return {
        "question": question,
        "category": category,
        "models": evaluated,
        "sourcegraph": {
            "connected": bool(
                context.get("sourcegraph")
            ),
            "query": question,
            "role": (
                "Repository search and evidence retrieval. "
                "Matches are supplied as repository context to the "
                "model and used by the live evaluator for grounding "
                "and unsupported-file checks. Sourcegraph does not "
                "generate or score the answer."
            ),
            "results": context.get(
                "sourcegraph",
                [],
            ),
        },
        "rag": {
            "retrieved": bool(
                context.get("rag")
            ),
            "role": (
                "Knowledge-base retrieval supplied alongside "
                "repository evidence as model context."
            ),
            "sources": context.get(
                "rag",
                [],
            ),
        },
        "comparison": comparison,
        "historical": load_historical(),
    }
