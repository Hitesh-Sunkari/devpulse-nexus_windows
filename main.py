# MEMORY PARSING
# ============================================================

def parse_memory_percentage(value):
    """
    Convert Docker memory percentage strings such as:

        '0.26%'

    into a float.

    Invalid values safely become 0.0.
    """

    if value is None:
        return 0.0

    try:
        return float(
            str(value)
            .replace("%", "")
            .strip()
        )

    except (ValueError, TypeError):
        return 0.0


def parse_memory_usage_bytes(value):
    """Read the used side of Docker's ``used / limit`` memory display."""
    match = re.match(
        r"\s*([0-9]+(?:\.[0-9]+)?)\s*([kmgtpe]?i?b|b)",
        str(value or ""),
        flags=re.IGNORECASE,
    )
    if not match:
        return 0

    amount = float(match.group(1))
    unit = match.group(2).lower()
    multipliers = {
        "b": 1,
        "kb": 1000,
        "mb": 1000 ** 2,
        "gb": 1000 ** 3,
        "tb": 1000 ** 4,
        "pb": 1000 ** 5,
        "eb": 1000 ** 6,
        "kib": 1024,
        "mib": 1024 ** 2,
        "gib": 1024 ** 3,
        "tib": 1024 ** 4,
        "pib": 1024 ** 5,
        "eib": 1024 ** 6,
    }
    return int(amount * multipliers.get(unit, 1))


